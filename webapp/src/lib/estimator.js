export const FORECAST_CAP_MIN = 30;

/**
 * Minutes until `ct` reaches `limit` at `ratePer10`, as a rounded range.
 * Returns { lo, hi } (minutes, multiples of 5, hi capped at 30),
 * or null when not rising or the central estimate is beyond the cap.
 */
export function forecastRange(ct, ratePer10, limit = THRESHOLDS.ACT_NOW_C) {
  if (ct == null || ratePer10 == null || ratePer10 < 0.05 || ct >= limit) return null;
  const est = (limit - ct) / (ratePer10 / 10);
  if (est > FORECAST_CAP_MIN) return null;
  // Under 5 min: never show a range that starts later than the estimate itself
  if (est < 5) return { lo: 0, hi: 5 };
  let lo = Math.max(5, Math.floor(est * 0.6 / 5) * 5);
  let hi = Math.min(FORECAST_CAP_MIN, Math.max(lo + 5, Math.ceil(est * 1.4 / 5) * 5));
  return { lo, hi };
}

/** "in about 10–25 min", or "within 5 min" when it is closer than that */
export function formatRange(r) {
  if (!r) return '';
  return r.lo === 0 ? `within ${r.hi} min` : `in about ${r.lo}–${r.hi} min`;
}

/**
 * Single recommended action string based on current state.
 */
export function recommendedAction(status) {
  if (status === 'Act Now')           return 'You are too hot. Stop now and tell your coach.';
  if (status === 'Watch')             return 'You are heating up. Take your break now, not in 10 minutes.';
  if (status === 'Cannot Estimate')   return 'Sit for a few minutes. If you feel dizzy or sick, stop and tell someone.';
  return 'Keep going. You are on a safe pace.';
}
