import { THRESHOLDS } from './datastore.js';

/**
 * estimator.js — trend and forecast helpers, plus a JS mirror of the firmware Kalman filter.
 *
 * The displayed forecast is a range from the last 10 minutes' trend
 * (forecastRange). projectForward is kept for the Phase 2 filter-agreement
 * test; it is not used on screen.
 *
 * Constants mirror ember_firmware.ino exactly. Do not retype them.
 */

// ─── ECTemp published params (Buller et al. 2013 / USARIEM TR T17-08) ────────
const B2 = -4.5714;
const B1 =  384.4286;
const B0 = -7887.1;

// Process noise per minute, observation noise (variance)
const GAMMA_SQ_PER_MIN = 0.000484;
const SIGMA_SQ         = 356.4544;

const CT_MIN = 35.0;
const CT_MAX = 41.5;
const STEP_S = 5;       // firmware step interval in seconds
const GAMMA_SQ_STEP = GAMMA_SQ_PER_MIN * (STEP_S / 60);

function hrFromCt(ct) {
  return B2 * ct * ct + B1 * ct + B0;
}

function dhrDct(ct) {
  return 2 * B2 * ct + B1;
}

/**
 * Run one Kalman step.
 * Returns { ct, vv } updated state.
 */
function filterStep(ct, vv, hr) {
  const ctPred = ct;
  const vPred  = vv + GAMMA_SQ_STEP;
  const slope  = dhrDct(ctPred);
  const denom  = slope * slope * vPred + SIGMA_SQ;
  const k      = denom !== 0 ? (vPred * slope) / denom : 0;
  const ctNew  = ctPred + k * (hr - hrFromCt(ctPred));
  const vvNew  = Math.max(0, (1 - k * slope) * vPred);
  return { ct: ctNew, vv: vvNew };
}

/**
 * Project core temperature forward by `horizonSeconds` seconds.
 *
 * @param {number}   ctNow         current estimate (°C)
 * @param {number}   vvNow         current Kalman variance
 * @param {number[]} hrHistory     array of recent HR readings (newest last)
 * @param {number}   horizonSeconds how far ahead to project (default 300 = 5 min)
 * @returns {{ points: Array<{t, ct}>, timeToLimitS: number|null }}
 */
export function projectForward(ctNow, vvNow, hrHistory, horizonSeconds = 300) {
  if (!ctNow || !hrHistory || hrHistory.length === 0) {
    return { points: [], timeToLimitS: null };
  }

  // Use median of recent HR as the projected future HR (conservative)
  const sorted = [...hrHistory].sort((a, b) => a - b);
  const medianHr = sorted[Math.floor(sorted.length / 2)];

  let ct = ctNow;
  let vv = vvNow ?? 0.5;
  const steps = Math.ceil(horizonSeconds / STEP_S);
  const points = [{ t: 0, ct }];
  let timeToLimitS = null;

  for (let i = 0; i < steps; i++) {
    const result = filterStep(ct, vv, medianHr);
    ct = Math.min(Math.max(result.ct, CT_MIN), CT_MAX);
    vv = result.vv;
    const tS = (i + 1) * STEP_S;
    points.push({ t: tS, ct });

    if (timeToLimitS === null && ct >= THRESHOLDS.ACT_NOW_C) {
      timeToLimitS = tS;
    }
  }

  return { points, timeToLimitS };
}

/**
 * Rate of change of the estimate, in °C per 10 min, from a least-squares line
 * through the per-minute history over the last `windowMin` minutes.
 * Returns { ratePer10, spanMin } or null when there is too little data.
 */
export function trendRate(history, now, windowMin = 10, minSpanMin = 3) {
  if (!history || history.length < 2) return null;
  const pts = history.filter(h => h.ctEst != null && h.t >= now - windowMin * 60_000);
  if (pts.length < 2) return null;
  const spanMin = (pts[pts.length - 1].t - pts[0].t) / 60_000;
  if (spanMin < minSpanMin) return null;
  const n  = pts.length;
  const mx = pts.reduce((a, p) => a + p.t, 0) / n;
  const my = pts.reduce((a, p) => a + p.ctEst, 0) / n;
  let sxy = 0, sxx = 0;
  for (const p of pts) { sxy += (p.t - mx) * (p.ctEst - my); sxx += (p.t - mx) ** 2; }
  if (sxx === 0) return null;
  return { ratePer10: (sxy / sxx) * 600_000, spanMin };
}

/** "↑ 0.3° / 10 min", "↓ 0.2° / 10 min", "→ Steady", or "—" without enough data. */
export function formatTrend(trend) {
  if (!trend) return '—';
  const r = trend.ratePer10;
  if (Math.abs(r) < 0.1) return '→ Steady';
  return `${r > 0 ? '↑' : '↓'} ${Math.abs(r).toFixed(1)}° / 10 min`;
}

